"""``alembic check`` through the migration environment (``migrations/env.py``).

``test_schema_sync`` compares the models with the migrated schema by calling Alembic's
comparison itself. This runs Alembic's own command with the options ``env.py`` gives
it, which are what ``alembic revision --autogenerate`` uses: a developer who generates a
migration should get exactly the changes they made and nothing else. Server defaults
count (an identity column and ``DEFAULT 8`` are compared only when asked), and the
monthly partitions of ``audit_event``, which ``ensure_partitions`` creates and no model
declares, are not proposed for deletion.
"""

import pytest
from alembic import command
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Engine, text

from xolotl.platform.migrate import alembic_config

DEFAULT = "ALTER TABLE job ALTER COLUMN max_attempts SET DEFAULT {}"


def test_autogenerate_proposes_nothing_for_a_migrated_database(admin_engine: Engine):
    command.check(alembic_config())  # raises AutogenerateDiffsDetected on any change


def test_autogenerate_notices_a_server_default_that_drifted(admin_engine: Engine):
    with admin_engine.begin() as conn:
        _ = conn.execute(text(DEFAULT.format(9)))
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="max_attempts"):
            command.check(alembic_config())
    finally:
        with admin_engine.begin() as conn:
            _ = conn.execute(text(DEFAULT.format(8)))
    command.check(alembic_config())  # and the database is as it was
