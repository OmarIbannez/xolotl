r"""``render.yaml``, the Render Blueprint, checked against the code it deploys.

Render reads the file only when a Blueprint syncs, so a misspelled variable (which
Settings would silently ignore), a moved path or a literal secret would surface as a
broken or leaky deploy. These tests read it as data and hold it to the Settings, the
Dockerfile, the health route, CI and docker-compose. docs/deploy-render.md explains
each choice.

Render's own vocabulary (keys, plans, regions) is checked against the JSON Schema
Render publishes at https://render.com/schema/render.yaml.json, vendored verbatim as
``tests/fixtures/render-blueprint.schema.json`` on 2026-10-19 so that CI needs no
network. It is refreshed by hand when Render's Blueprint documentation changes::

    curl -sSL https://render.com/schema/render.yaml.json \
        -o tests/fixtures/render-blueprint.schema.json
"""

import base64
import copy
import json
import os
import re
import secrets
from pathlib import Path, PurePosixPath
from typing import Any, cast

import pytest
import yaml
from jsonschema import Draft202012Validator
from jsonschema.exceptions import ValidationError
from sqlalchemy import make_url

from xolotl.platform.api.health import router as health_router
from xolotl.platform.config import APP_ROLE, Settings

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "tests" / "fixtures" / "render-blueprint.schema.json"
# Names that hold a secret: none may carry a literal value in the file.
SECRET_NAME = re.compile(r"SECRET|PASSWORD|KEY|TOKEN|DATABASE_(ADMIN_)?URL")
# The shape of Render's connectionString: the private network, no port.
CONNECTION_STRING = "postgresql://xolotl:owner-from-render@dpg-d1abc-a/xolotl"
# The COPY sources that only feed package metadata, not the running service.
METADATA_ONLY = {"README.md"}


def load(name: str) -> dict[Any, Any]:
    return cast("dict[Any, Any]", yaml.safe_load((ROOT / name).read_text()))


def blueprint() -> dict[str, Any]:
    return load("render.yaml")


def schema() -> dict[str, Any]:
    return cast("dict[str, Any]", json.loads(SCHEMA.read_text()))


def web_service() -> dict[str, Any]:
    services = [s for s in blueprint()["services"] if s["type"] == "web"]
    assert len(services) == 1, "expected exactly one web service"
    return services[0]


def env_vars() -> dict[str, dict[str, Any]]:
    return {var["key"]: var for var in web_service()["envVars"]}


def generated() -> str:
    # What generateValue makes: "a randomized, base64-encoded, 256-bit value". The
    # operator's `openssl rand -base64 32` has the same shape.
    return base64.b64encode(secrets.token_bytes(32)).decode()


def render_environment() -> dict[str, str]:
    """Resolve the Blueprint's variables the way Render would, with stand-ins.

    Returns:
        The service's environment, PORT included (Render sets it).

    """
    resolved = {"PORT": "10000"}
    for key, var in env_vars().items():
        if "value" in var:
            resolved[key] = str(var["value"])
        elif "fromDatabase" in var:
            resolved[key] = CONNECTION_STRING
        else:  # generated by Render, or pasted by the operator (sync: false)
            resolved[key] = generated()
    return resolved


def dockerfile() -> str:
    return (ROOT / "Dockerfile").read_text()


def copy_sources() -> list[str]:
    sources: list[str] = []
    for line in dockerfile().splitlines():
        words = line.split()
        if not words or words[0] != "COPY":
            continue
        args = [w for w in words[1:] if not w.startswith("--")]
        if any(w.startswith("--from=") for w in words):
            continue  # from another stage or image, not the repository
        sources.extend(a.rstrip("/") for a in args[:-1])
    return sources


def covered(path: str, patterns: list[str]) -> bool:
    for pattern in patterns:
        if pattern.endswith("/**"):
            base = pattern.removesuffix("/**")
            if path == base or path.startswith(f"{base}/"):
                return True
        elif path == pattern:
            return True
    return False


def describe(error: ValidationError) -> str:
    path = "/".join(str(p) for p in error.absolute_path) or "<root>"
    return f"{path}: {error.message}"


def violations(error: ValidationError) -> list[str]:
    """Describe ``error`` down to its leaves.

    Returns:
        One ``path: message`` line per leaf: the error itself when it has no
        branches, otherwise every leaf under its ``anyOf`` branches, which say what
        the branch rejected where the parent only dumps the instance.

    """
    if not error.context:
        return [describe(error)]
    return [line for branch in error.context for line in violations(branch)]


def test_the_service_builds_this_dockerfile_and_starts_with_its_cmd():
    service = web_service()
    assert (service["runtime"], service["dockerContext"]) == ("docker", ".")
    assert (ROOT / service["dockerfilePath"]).is_file()
    # No start or pre-deploy override: serve, exec form, is PID 1 and gets SIGTERM
    # itself, and it bootstraps and migrates on start (see the doc).
    for override in ("dockerCommand", "startCommand", "preDeployCommand"):
        assert override not in service
    (cmd,) = re.findall(r"^CMD (.+)$", dockerfile(), re.MULTILINE)
    assert json.loads(cmd) == ["xolotl", "serve"]


def test_the_health_check_is_the_readiness_route():
    path = web_service()["healthCheckPath"]
    assert path == "/readyz"
    assert path in {getattr(route, "path", None) for route in health_router.routes}


def test_every_variable_is_a_setting():
    # Settings ignores names it does not know: a typo would keep the default.
    for key in env_vars():
        assert key.startswith("XOLOTL_"), key
        assert key.removeprefix("XOLOTL_").lower() in Settings.model_fields, key


def test_no_secret_has_a_literal_value():
    secret = {key: var for key, var in env_vars().items() if SECRET_NAME.search(key)}
    assert set(secret) >= {
        "XOLOTL_DATABASE_ADMIN_URL",
        "XOLOTL_APP_DB_PASSWORD",
        "XOLOTL_JWT_SECRET",
        "XOLOTL_MASTER_KEY",
    }
    for key, var in secret.items():
        assert "value" not in var, key
        sources = (
            var.get("generateValue") is True,
            var.get("sync") is False,
            "fromDatabase" in var,
        )
        assert sources.count(True) == 1, key


def test_the_operator_pastes_one_secret_the_master_key():
    prompted = [key for key, var in env_vars().items() if var.get("sync") is False]
    # Not generated: the operator keeps the only copy outside Render.
    assert prompted == ["XOLOTL_MASTER_KEY"]


def test_literal_values_are_strings():
    # An unquoted `true` would reach Render as a YAML boolean.
    for key, var in env_vars().items():
        if "value" in var:
            assert isinstance(var["value"], str), key


def test_the_database_reference_exists():
    databases = {db["name"]: db for db in blueprint()["databases"]}
    references = [v["fromDatabase"] for v in env_vars().values() if "fromDatabase" in v]
    assert references == [{"name": "xolotl-db", "property": "connectionString"}]
    assert set(databases) == {"xolotl-db"}
    assert databases["xolotl-db"]["region"] == web_service()["region"]


def test_the_database_runs_the_postgres_the_tests_and_compose_run():
    (database,) = blueprint()["databases"]
    compose_image = load("docker-compose.yml")["services"]["db"]["image"]
    assert database["postgresMajorVersion"] == "17"
    assert compose_image.startswith(f"postgres:{database['postgresMajorVersion']}-")


def test_the_object_store_lives_on_the_disk():
    service = web_service()
    mount = PurePosixPath(service["disk"]["mountPath"])
    root = PurePosixPath(env_vars()["XOLOTL_OBJECT_STORE_ROOT"]["value"])
    assert mount.is_absolute()
    assert root.is_relative_to(mount)
    # Render's shell and SSH refuse a disk on the running user's home directory.
    assert not mount.is_relative_to("/home")
    assert mount != PurePosixPath("/app")


def test_one_instance_on_a_paid_plan_runs_the_worker():
    service = web_service()
    # A disk attaches to one instance, and every instance would run its own worker.
    assert service.get("numInstances", 1) == 1
    assert "scaling" not in service
    assert env_vars()["XOLOTL_EMBEDDED_WORKER"]["value"] == "true"
    # Free web services have no disk and no shell; free databases expire.
    assert service["plan"] != "free"
    assert blueprint()["databases"][0]["plan"] != "free"


def test_auto_deploys_wait_for_the_ci_that_runs_on_the_tracked_branch():
    service = web_service()
    assert service["autoDeployTrigger"] in {"commit", "checksPass"}
    if service["autoDeployTrigger"] == "checksPass":
        # Render skips a commit on which zero checks ran.
        ci = load(".github/workflows/ci.yml")
        triggers = ci[True]  # YAML 1.1 reads the bare key `on` as the boolean true
        assert service["branch"] in triggers["push"]["branches"]


def test_the_build_filter_covers_everything_the_image_copies():
    paths = web_service()["buildFilter"]["paths"]
    assert {"Dockerfile", ".dockerignore"} <= set(paths)
    for source in copy_sources():
        if source not in METADATA_ONLY:
            assert covered(source, paths), source


def test_the_image_carries_the_policy_packs():
    assert "policy-packs" in copy_sources()
    assert "policy-packs/**" in web_service()["buildFilter"]["paths"]


def test_the_environment_render_gives_is_a_valid_production_configuration(
    monkeypatch: pytest.MonkeyPatch,
):
    for key in list(os.environ):
        if key.upper().startswith("XOLOTL_") or key.upper() == "PORT":
            monkeypatch.delenv(key)
    environment = render_environment()
    for key, value in environment.items():
        monkeypatch.setenv(key, value)
    settings = cast("Any", Settings)(_env_file=None)
    assert (settings.env, settings.port, settings.embedded_worker) == (
        "prod",
        10000,
        True,
    )
    app_url, admin_url = (
        make_url(settings.database_url),
        make_url(settings.database_admin_url),
    )
    assert (app_url.username, app_url.password) == (
        APP_ROLE,
        environment["XOLOTL_APP_DB_PASSWORD"],
    )
    assert app_url.drivername == admin_url.drivername == "postgresql+psycopg"
    assert app_url.host == admin_url.host == "dpg-d1abc-a"
    assert settings.object_store_root == Path(environment["XOLOTL_OBJECT_STORE_ROOT"])
    assert settings.connector_mode_default == "LIVE"


def test_the_database_accepts_only_private_network_connections():
    (database,) = blueprint()["databases"]
    assert database["ipAllowList"] == []


def test_the_vendored_schema_is_renders():
    vendored = schema()
    assert vendored["$id"] == "https://render.com/schema/render.yaml.json"
    Draft202012Validator.check_schema(vendored)  # raises SchemaError when malformed


def test_the_blueprint_is_valid_against_renders_schema():
    errors = [
        describe(e) for e in Draft202012Validator(schema()).iter_errors(blueprint())
    ]
    assert errors == []


def test_the_schema_catches_an_unknown_key_and_an_unknown_plan():
    broken = copy.deepcopy(blueprint())
    (service,) = [s for s in broken["services"] if s["type"] == "web"]
    service["healthcheckPath"] = service.pop("healthCheckPath")
    broken["databases"][0]["plan"] = "0.1c-256mbb"
    errors = [
        line
        for error in Draft202012Validator(schema()).iter_errors(broken)
        for line in violations(error)
    ]
    # A service is an anyOf over Render's service kinds: the web-service branch knows
    # every other key in the file and rejects the typo alone.
    index = broken["services"].index(service)
    assert (
        f"services/{index}: Additional properties are not allowed "
        "('healthcheckPath' was unexpected)"
    ) in errors
    assert any(
        e.startswith("databases/0/plan: '0.1c-256mbb' is not one of [") for e in errors
    )
